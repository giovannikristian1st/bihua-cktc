-- 1. TABEL TASKS (Menyimpan Tugas yang dibuat Guru)
CREATE TABLE IF NOT EXISTS public.tasks (
    id TEXT PRIMARY KEY,
    payload TEXT NOT NULL,
    teacher_name TEXT,
    class TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABEL SUBMISSIONS (Menyimpan Hasil Pengerjaan & Nilai Murid)
CREATE TABLE IF NOT EXISTS public.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
    class TEXT NOT NULL,
    student_name TEXT NOT NULL,
    mistakes_count INTEGER DEFAULT 0,
    total_words INTEGER DEFAULT 0,
    repetitions INTEGER DEFAULT 1,
    duration NUMERIC DEFAULT 0,
    mistakes_detail TEXT,
    status TEXT DEFAULT 'Selesai',
    submitted_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index agar pencarian Leaderboard & Hasil Tugas super cepat (<10ms)
CREATE INDEX IF NOT EXISTS idx_submissions_task_id ON public.submissions(task_id);
CREATE INDEX IF NOT EXISTS idx_submissions_class ON public.submissions(class);
CREATE INDEX IF NOT EXISTS idx_submissions_student_name ON public.submissions(student_name);

-- 3. TABEL TEACHERS (Menyimpan Pengaturan Guru & Kelas Bimbingan)
CREATE TABLE IF NOT EXISTS public.teachers (
    name TEXT PRIMARY KEY,
    classes JSONB DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABEL STUDENTS (Daftar Siswa per Kelas)
CREATE TABLE IF NOT EXISTS public.students (
    class TEXT PRIMARY KEY,
    names JSONB DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. TABEL STUDENT THEMES (Pilihan Tema Murid)
CREATE TABLE IF NOT EXISTS public.student_themes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class TEXT NOT NULL,
    student_name TEXT NOT NULL,
    theme TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(class, student_name)
);

-- Aktifkan Row Level Security (RLS) dengan Akses Terbuka untuk Web App
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.teachers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.student_themes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public all on tasks" ON public.tasks;
DROP POLICY IF EXISTS "Allow public all on submissions" ON public.submissions;
DROP POLICY IF EXISTS "Allow public all on teachers" ON public.teachers;
DROP POLICY IF EXISTS "Allow public all on students" ON public.students;
DROP POLICY IF EXISTS "Allow public all on student_themes" ON public.student_themes;

CREATE POLICY "Allow public all on tasks" ON public.tasks FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on submissions" ON public.submissions FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on teachers" ON public.teachers FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on students" ON public.students FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on student_themes" ON public.student_themes FOR ALL USING (true) WITH CHECK (true);
